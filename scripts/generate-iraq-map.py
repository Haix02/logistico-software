#!/usr/bin/env python3
"""Generates src/Logistico.Web.Client/Ui/Map/IraqMapShapes.g.cs: SVG outlines of Iraq's governorates.

Source: geoBoundaries gbOpen IRQ ADM1 (2022, simplified), CC0 1.0 public domain.
The outlines are projected (equirectangular, scaled by cos(latitude)), simplified with Douglas–Peucker and
written as SVG path strings, so the network map needs no map library, tile server or internet connection.

Usage: python3 -I scripts/generate-iraq-map.py   (re-run only to change the source or the detail level)
"""
import json
import math
import os
import sys
import urllib.request

SOURCE = ("https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/IRQ/ADM1/"
          "geoBoundaries-IRQ-ADM1_simplified.geojson")
WIDTH = 600.0          # SVG units across the country
TOLERANCE = 0.012      # degrees; larger = fewer points
PAD = 8.0

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "Logistico.Web.Client", "Ui", "Map", "IraqMapShapes.g.cs")


def load():
    with urllib.request.urlopen(SOURCE, timeout=60) as response:
        return json.load(response)


def rings(geometry):
    polys = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    for poly in polys:
        yield poly[0]  # outer ring only; Iraq's governorates have no holes that matter at this scale


def perpendicular(p, a, b):
    if a == b:
        return math.dist(p, a)
    (x, y), (x1, y1), (x2, y2) = p, a, b
    return abs((y2 - y1) * x - (x2 - x1) * y + x2 * y1 - y2 * x1) / math.dist(a, b)


def simplify(points, tolerance):
    if len(points) < 4:
        return points
    index, best = 0, 0.0
    for i in range(1, len(points) - 1):
        d = perpendicular(points[i], points[0], points[-1])
        if d > best:
            index, best = i, d
    if best <= tolerance:
        return [points[0], points[-1]]
    return simplify(points[: index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


def main():
    data = load()
    features = data["features"]
    all_pts = [pt for f in features for ring in rings(f["geometry"]) for pt in ring]
    min_lon = min(p[0] for p in all_pts)
    max_lon = max(p[0] for p in all_pts)
    min_lat = min(p[1] for p in all_pts)
    max_lat = max(p[1] for p in all_pts)
    k = math.cos(math.radians((min_lat + max_lat) / 2))
    scale = (WIDTH - 2 * PAD) / ((max_lon - min_lon) * k)
    height = (max_lat - min_lat) * scale + 2 * PAD

    def project(lon, lat):
        return (PAD + (lon - min_lon) * k * scale, PAD + (max_lat - lat) * scale)

    shapes = []
    for f in sorted(features, key=lambda f: f["properties"]["shapeISO"]):
        code = f["properties"]["shapeISO"]
        parts, area_sum, cx_sum, cy_sum = [], 0.0, 0.0, 0.0
        for ring in rings(f["geometry"]):
            pts = [project(lon, lat) for lon, lat in simplify([tuple(p) for p in ring], TOLERANCE)]
            if len(pts) < 3:
                continue
            parts.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")
            for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
                cross = x0 * y1 - x1 * y0
                area_sum += cross
                cx_sum += (x0 + x1) * cross
                cy_sum += (y0 + y1) * cross
        cx, cy = cx_sum / (3 * area_sum), cy_sum / (3 * area_sum)
        shapes.append((code, "".join(parts), cx, cy))

    lines = [
        "// <auto-generated>",
        "// Generated by scripts/generate-iraq-map.py from geoBoundaries IRQ ADM1 (CC0 1.0). Do not edit.",
        "// </auto-generated>",
        "namespace Logistico.Web.Client.Ui.Map;",
        "",
        "internal static class IraqMapShapes",
        "{",
        f"    public const double Width = {WIDTH:.0f};",
        f"    public const double Height = {height:.0f};",
        "",
        "    // Projection used for the outlines: x = Pad + (lon - MinLon) * XPerDegree, y = Pad + (MaxLat - lat) * YPerDegree.",
        f"    public const double Pad = {PAD:.1f};",
        f"    public const double MinLon = {min_lon:.6f};",
        f"    public const double MaxLat = {max_lat:.6f};",
        f"    public const double XPerDegree = {k * scale:.6f};",
        f"    public const double YPerDegree = {scale:.6f};",
        "",
        "    /// <summary>Governorate outlines (ISO 3166-2:IQ code, SVG path, label anchor).</summary>",
        "    public static readonly IReadOnlyList<GovernorateShape> Governorates =",
        "    [",
    ]
    for code, path, cx, cy in shapes:
        lines.append(f'        new("{code}", "{path}", {cx:.1f}, {cy:.1f}),')
    lines += [
        "    ];",
        "",
        "    /// <summary>Map position of a place given in degrees (warehouses, hubs).</summary>",
        "    public static (double X, double Y) Project(double latitude, double longitude) =>",
        "        (Pad + (longitude - MinLon) * XPerDegree, Pad + (MaxLat - latitude) * YPerDegree);",
        "",
        "    /// <summary>Degrees for a map position (placing a warehouse by clicking the map).</summary>",
        "    public static (double Latitude, double Longitude) Unproject(double x, double y) =>",
        "        (MaxLat - (y - Pad) / YPerDegree, MinLon + (x - Pad) / XPerDegree);",
        "}",
        "",
        "internal sealed record GovernorateShape(string Code, string Path, double LabelX, double LabelY);",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    points = sum(p.count("L") + 1 for _, p, _, _ in shapes)
    print(f"{len(shapes)} governorates, {points} points, {WIDTH:.0f}x{height:.0f} -> {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
