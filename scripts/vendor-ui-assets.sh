#!/usr/bin/env bash
# Downloads pinned UI assets into src/Logistico.Web/wwwroot/lib so the app never depends on a CDN at runtime.
#   Blueprint (Palantir) core + select CSS and icon fonts — Apache-2.0
#   Almarai web font (Arabic + Latin, weights 300/400/700/800) — SIL Open Font License 1.1
# Right-to-left copies of the Blueprint stylesheets (*.rtl.css) are generated with RTLCSS, the same way
# Bootstrap produces its RTL build, so Arabic pages get correctly mirrored controls without hand-written overrides.
# Requires: curl, python3, node/npx (for RTLCSS).
# Usage: scripts/vendor-ui-assets.sh   (re-run after changing a version below)
set -euo pipefail

BLUEPRINT_CORE=6.21.0
BLUEPRINT_SELECT=6.4.0
BLUEPRINT_ICONS=6.14.1
ALMARAI=5.3.0
RTLCSS=4.3.0

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/src/Logistico.Web/wwwroot/lib"
CDN="https://cdn.jsdelivr.net/npm"
rm -rf "$OUT/plex-arabic" "$OUT/cairo" "$OUT/noto-naskh-arabic"
mkdir -p "$OUT/blueprint" "$OUT/almarai"

fetch() { curl -fsSL --retry 3 "$1" -o "$2"; }

# Blueprint stylesheets and licence
fetch "$CDN/@blueprintjs/core@$BLUEPRINT_CORE/lib/css/blueprint.css" "$OUT/blueprint/blueprint.css"
fetch "$CDN/@blueprintjs/select@$BLUEPRINT_SELECT/lib/css/blueprint-select.css" "$OUT/blueprint/blueprint-select.css"
fetch "$CDN/@blueprintjs/core@$BLUEPRINT_CORE/LICENSE" "$OUT/blueprint/LICENSE"

# Mirrored (right-to-left) builds for Arabic
for sheet in blueprint blueprint-select; do
  npx --yes "rtlcss@$RTLCSS" --silent "$OUT/blueprint/$sheet.css" "$OUT/blueprint/$sheet.rtl.css"
done

# Blueprint icon fonts (16 px and 20 px grids)
for size in 16 20; do
  for ext in woff2 woff; do
    fetch "$CDN/@blueprintjs/icons@$BLUEPRINT_ICONS/lib/css/blueprint-icons-$size.$ext" "$OUT/blueprint/blueprint-icons-$size.$ext"
  done
done

# Icon classes (.bp6-icon-<name>::before) generated from Blueprint's codepoint map
fetch "$CDN/@blueprintjs/icons@$BLUEPRINT_ICONS/lib/esm/generated/16px/blueprint-icons-16.js" "$OUT/blueprint/.codepoints.js"
python3 -I - "$OUT/blueprint/.codepoints.js" "$OUT/blueprint/blueprint-icons.css" <<'PY'
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
names = dict(re.findall(r'BlueprintIcons_16\["(\w+)"\] = "([a-z0-9-]+)"', src))
codes = re.findall(r'\[BlueprintIcons_16\.(\w+)\]: "(\d+)"', src)
lines = [
    "/* Generated by scripts/vendor-ui-assets.sh from @blueprintjs/icons (Apache-2.0). Do not edit. */",
    '@font-face { font-family: "blueprint-icons-16"; src: url("blueprint-icons-16.woff2") format("woff2"), url("blueprint-icons-16.woff") format("woff"); font-display: block; }',
    '@font-face { font-family: "blueprint-icons-20"; src: url("blueprint-icons-20.woff2") format("woff2"), url("blueprint-icons-20.woff") format("woff"); font-display: block; }',
]
seen = set()
for key, code in codes:
    name = names.get(key)
    if not name or name in seen:
        continue
    seen.add(name)
    lines.append(f'.bp6-icon-{name}::before {{ content: "\\{int(code):x}"; }}')
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"blueprint icons: {len(seen)} classes")
PY
rm -f "$OUT/blueprint/.codepoints.js"

# Almarai web font (weights 300, 400, 700, 800): Arabic and Latin subsets
: > "$OUT/almarai/.raw.css"
for weight in 300 400 700 800; do
  for subset in arabic latin; do
    fetch "$CDN/@fontsource/almarai@$ALMARAI/files/almarai-$subset-$weight-normal.woff2" "$OUT/almarai/almarai-$subset-$weight.woff2"
  done
  curl -fsSL --retry 3 "$CDN/@fontsource/almarai@$ALMARAI/$weight.css" >> "$OUT/almarai/.raw.css"
  echo "" >> "$OUT/almarai/.raw.css"
done
fetch "$CDN/@fontsource/almarai@$ALMARAI/LICENSE" "$OUT/almarai/LICENSE"
python3 -I - "$OUT/almarai/.raw.css" "$OUT/almarai/almarai.css" <<'PY'
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
src = src.replace("'Almarai'", '"Almarai"')
src = re.sub(
    r"url\(\./files/almarai-([a-z-]+)-(\d+)-normal\.woff2\)\s*format\('woff2'\),\s*url\(\./files/almarai-[a-z-]+-\d+-normal\.woff\)\s*format\('woff'\)",
    r'url("almarai-\1-\2.woff2") format("woff2")',
    src,
)
open(sys.argv[2], "w", encoding="utf-8").write("/* Generated by scripts/vendor-ui-assets.sh from @fontsource/almarai (OFL-1.1). Do not edit. */\n" + src)
PY
rm -f "$OUT/almarai/.raw.css"

echo "UI assets vendored into $OUT"
