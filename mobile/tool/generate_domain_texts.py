#!/usr/bin/env python3
"""Generates lib/l10n/domain_texts.g.dart from the server's own texts, so the app names statuses, reasons and
governorates exactly as the web console does. Run from mobile/: python3 tool/generate_domain_texts.py [--check]"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESX = ROOT / "src/Modules/Shipments/Logistico.Modules.Shipments.Contracts/Resources/ShipmentTexts{}.resx"
GOVERNORATES = ROOT / "src/Logistico.SharedKernel/Iraq/IraqGovernorates.cs"
OUT = Path(__file__).resolve().parents[1] / "lib/l10n/domain_texts.g.dart"
PREFIXES = ("Status_", "Failure_", "Receiver_", "ShelfState_", "Alert_", "Severity_", "Return_", "Payout_", "Scan_")


def texts(suffix):
    root = ET.parse(str(RESX).format(suffix)).getroot()
    return {d.get("name"): d.find("value").text or "" for d in root.findall("data") if d.get("name", "").startswith(PREFIXES)}


def dart(value):
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def generate():
    en, ar = texts(""), texts(".ar")
    keys = sorted(set(en) & set(ar))
    places = re.findall(r'new\("(IQ-[A-Z]{2})", "([^"]+)", "([^"]+)"', GOVERNORATES.read_text(encoding="utf-8"))
    lines = [
        "// GENERATED by tool/generate_domain_texts.py from the server's ShipmentTexts and IraqGovernorates. Do not edit.",
        "",
        "/// Domain words (statuses, reasons, alerts…) in English and Arabic, keyed like the server's resources.",
        "const Map<String, Map<String, String>> domainTexts = {",
    ]
    for lang, source in (("en", en), ("ar", ar)):
        lines.append(f"  '{lang}': {{")
        lines += [f"    {dart(k)}: {dart(source[k])}," for k in keys]
        lines.append("  },")
    lines += ["};", "", "/// Iraq's governorates: code, English name, Arabic name.", "const List<(String, String, String)> governorates = ["]
    lines += [f"  ({dart(c)}, {dart(e)}, {dart(a)})," for c, e, a in places]
    lines += ["];", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    content = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            sys.exit("lib/l10n/domain_texts.g.dart is out of date: run python3 tool/generate_domain_texts.py")
    else:
        OUT.write_text(content, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} ({content.count(chr(10))} lines)")
